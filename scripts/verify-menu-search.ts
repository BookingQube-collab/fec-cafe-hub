import assert from 'node:assert/strict';
import fs from 'node:fs';
import { matchesMenuSearch, menuSearchIndex, menuSearchQuery } from '../client/src/lib/menuSearch';

const source = JSON.parse(fs.readFileSync('fixtures/urban-menu.json', 'utf8'));
const items = source.categories.flatMap((category: {title: string; items: [string, number, {label: string}[]?][]}) => category.items.map(([name, , options]) => ({name, category: category.title, index: menuSearchIndex({name}, category.title, options?.map(option => option.label))})));
const find = (query: string) => items.filter((item: {index: readonly string[]}) => matchesMenuSearch(item.index, menuSearchQuery(query))).map((item: {name: string}) => item.name);
assert.equal(find('').length, 70);
assert.equal(find('   ').length, 70);
assert.equal(find('pizza').length, 5, 'A category query includes items without the category in their name');
assert.equal(find('coffee').length, 21);
assert.equal(find('HOT COFFEE').length, 11);
assert.equal(find('iced coffee').length, 10);
assert.equal(find('coffee cold').length, 10, 'Words may be in a different order across name and category');
assert.equal(find('beverages').length, 44);
assert.equal(find('drinks').length, 44);
assert.equal(find('snack').length, 12);
assert.equal(find('desserts').length, 2);
assert.equal(find('ice cream').length, 2);
assert.equal(find('hotdog').length, 5);
assert.equal(find('cofee').length, 21);
assert.equal(find('cofefe').length, 21);
assert.equal(find('piza').length, 5);
assert.deepEqual(find('Margherita'), ['Marguareita']);
assert.deepEqual(find('pina colada'), ['Pinna Colada']);
assert.deepEqual(find('DOUBLE espresso'), ['Espresso Single/Double']);
assert.equal(find('juices').length, 3);
assert.equal(find('قَهْوَة').length, 21);
assert.equal(find('عصير').length, 3);
assert.deepEqual(find('cream mushroom'), ['Creamy Mushroom']);
assert.deepEqual(find('pizza espresso'), [], 'Unrelated words must not broaden the results');
assert.deepEqual(find('vegan'), [], 'Do not invent diet or ingredient claims');
assert.deepEqual(find('zzzzzzzz'), []);
assert.deepEqual(find('tea'), ['Karak', 'Black/Green Tea']);
assert.ok(!matchesMenuSearch(menuSearchIndex({name: 'Steak'}, 'Food'), menuSearchQuery('tea')), 'Short words must not match inside unrelated names');
assert.ok(matchesMenuSearch(menuSearchIndex({name: 'Seasonal bowl', description: 'Roasted aubergine', tags: ['Vegetarian']}, 'Bowls', ['Large']), menuSearchQuery('aubergine vegetarian large')));
assert.ok(matchesMenuSearch(menuSearchIndex({name: 'Crème brûlée'}, 'Desserts'), menuSearchQuery('creme brulee')));
console.log('PASS: real menu categories/items, equivalents, multiword queries, options, spelling tolerance, accents/Arabic, and irrelevant-query exclusions.');
