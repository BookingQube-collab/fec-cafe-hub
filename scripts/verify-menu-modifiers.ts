import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import fs from 'node:fs';
import { menuModifierGroupsSchema, insertMenuItemSchema } from '../shared/schema';
import { reconcileModifierSelections, selectedModifierOptions, missingModifierGroups, customizationTotal } from '../shared/menuCustomization';
import { modifierFixture } from './modifier-fixture';

const groups = menuModifierGroupsSchema.parse(modifierFixture);
const [sauce, toppings] = groups;
const ids = toppings.options.map(o => o.id);
const selected = { [sauce.id]: [sauce.options[1].id], [toppings.id]: [ids[0], ids[2]] };
const before = JSON.stringify({ groups, selected });
assert.deepEqual(missingModifierGroups(groups, {}), [sauce]);
assert.deepEqual(missingModifierGroups(groups, selected), []);
assert.equal(selectedModifierOptions(groups, selected).length, 3);
assert.equal(customizationTotal('20', '10', selectedModifierOptions(groups, selected)), '22.50');
assert.equal(customizationTotal('25', '20', selectedModifierOptions(groups, selected)), '24.50', 'Size discount affects base price; extras retain their listed prices');
assert.equal(customizationTotal('0.10', '0', [{ price: '0.20' }]), '0.30');
assert.equal(customizationTotal('10.01', '15', [{ price: '0.10' }]), '8.61');
assert.equal(customizationTotal('10', '100', [{ price: '3' }]), '3.00');
assert.equal(customizationTotal('20', null, []), '20.00');
assert.deepEqual(reconcileModifierSelections(groups, { [sauce.id]: [sauce.options[0].id, sauce.options[1].id], [toppings.id]: [ids[3], 'unknown', ids[0], ids[0], ids[1], ids[2]], orphan: ['unknown'] }), {
  [sauce.id]: [sauce.options[0].id], [toppings.id]: [ids[0], ids[1]],
});
const changed = structuredClone(groups);
changed[1].options[0].isAvailable = false;
changed[1].options = changed[1].options.filter(o => o.id !== ids[2]);
assert.deepEqual(selectedModifierOptions(changed, selected).map(o => o.id), [sauce.options[1].id]);
assert.equal(JSON.stringify({ groups, selected }), before, 'Reconciliation must not mutate source records or choices');
const reject = (modify: (value: typeof groups) => void) => { const value = structuredClone(groups); modify(value); assert.equal(menuModifierGroupsSchema.safeParse(value).success, false); };
reject(g => { g[0].maxSelections = 2; });
reject(g => { g[1].minSelections = 3; });
reject(g => { g[1].maxSelections = 5; });
reject(g => { g[1].options[0].price = '-1'; });
reject(g => { g[1].options[0].price = '1.001'; });
reject(g => { g[1].options[0].price = '100000000'; });
reject(g => { g[1].options[0].label = ' '; });
reject(g => { g[1].options[1].label = 'CHEESE'; });
reject(g => { g[1].options[0].id = g[0].options[0].id; });
reject(g => { g[1].id = g[0].id; });
reject(g => { g[1].title = g[0].title; });
reject(g => { g[1].options = []; });
reject(g => { g[1].maxSelections = 1.5; });
reject(g => { g[1].options[0].labelAr = 'a'.repeat(81); });
reject(g => { g[1].options = Array.from({ length: 21 }, (_, i) => ({ id: randomUUID(), label: `Choice ${i}`, price: '0', isAvailable: true })); });
reject(g => { for (let i = 2; i < 9; i++) g.push({ ...structuredClone(sauce), id: randomUUID(), title: `Group ${i}`, options: [{ ...sauce.options[0], id: randomUUID() }] }); });
assert.deepEqual(menuModifierGroupsSchema.parse([]), []);
assert.equal(insertMenuItemSchema.partial().parse({ isAvailable: false }).modifierGroups, undefined, 'Visibility changes must not clear customization');
assert.equal(groups[0].titleAr, 'اختر الصلصة');
assert.equal(groups[1].options[0].labelAr, 'جبن');
fs.writeFileSync('data/menu-modifiers-verification.json', JSON.stringify({ passed: true, groups: groups.length, bilingualLabels: true, centAccurateTotals: true, selectionLimits: true, unavailableChoices: true, validation: true, checkedAt: new Date().toISOString() }, null, 2));
console.log('PASS: customization validation, single/multiple limits, availability, Arabic labels, discounts and cent-accurate estimated totals.');
